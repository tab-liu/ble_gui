/**modbus协议的标准CRC16,公式法，等效于查表法
*@brief??
*@param[in]pbBuf，待校验的数据指针；num待校验的数据字节数
*@param[out]None
*@return CRC16结果
20230817 温丹基于协议确认增加
*/
uint16_t CalcCrc16_modbus(const uint8_t *pbBuf, uint16_t num) 
{
    uint16_t u16CRC = 0xFFFF;
    uint16_t i =0;   
    
#ifdef USED_CRC16_MODBUS_FIND_TABLE
    while(num--) {
        u16CRC = ((u16CRC >> 8) & 0xFF) ^ md_crc_tbl[(u16CRC ^ *pbBuf++) & 0xFF];
    }
#else    
	while(num--)
	{
		u16CRC ^= *pbBuf;//*addr++
		if(num >= 1)
		{
			pbBuf++;//最后一个不++
		}
		for (i = 0; i < 8; i++)
		{
			if (u16CRC & 1)
			{
				u16CRC >>= 1;
				u16CRC ^= 0xA001;
			}
			else
			{
				u16CRC >>= 1;
			}
		}
	}
#endif  

    return u16CRC;  
}

