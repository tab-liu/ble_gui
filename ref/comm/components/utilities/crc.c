/*******************************************************************************
函数名称： CalcCrc16_Xmodem
功能描述： 查表计算CRC16-Xmodem
输入参数： ptr（指针） 数据起始地址 len 数据长度
输出参数： 无
返 回 值： crc 计算结果crc16
作    者： 李海洋
日    期： 2022.12.30
20230817 温丹更改备注：此函数是CRC16-Xmodem，不是CRC16-modbus
修改记录：
*******************************************************************************/
uint16_t CalcCrc16_Xmodem(const uint8_t *pdata, uint16_t len)//xmd_crc16_tlb
{
    volatile uint16_t crc = 0x0000;
    uint16_t i;
    
#ifdef USED_CRC16_XMODEM_FIND_TABLE
    for(i = 0; i < len; i++) {
        crc = (crc << 8) ^ CRC16_Xmodem_Table[(crc >> 8 ^ pdata[i]) & 0xFF];
    }
#else 
    while(len--)  {
        crc ^= *pdata++ << 8;
        for(i = 0; i < 8; i++) 
        {
            if( crc & 0x8000 )
                crc = (crc << 1) ^ 0x1021;
            else
                crc = crc << 1;
        }
    } 
#endif
    
    return  crc;
}




